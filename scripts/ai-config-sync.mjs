#!/usr/bin/env node
/**
 * syn — AI config sync (.claude/ → .cursor/)
 * ------------------------------------------------------------------
 * `.claude/` + `CLAUDE.md` are the SINGLE SOURCE OF TRUTH. This script
 * regenerates the whole `.cursor/` tree from them and validates the docs
 * against the actual Laravel + Vue codebase.
 *
 * Ground truth is derived from code — NOT from the docs:
 *   - composer.json           → PHP, Laravel, Inertia, test runner
 *   - package.json            → Vue, UI library, Tailwind, Zod, Pinia Colada
 *   - components.json         → shadcn-vue style + icon library
 *   - resources/js/app.ts     → PrimeVue unstyled mode (when PrimeVue is installed)
 *   - vite.config.ts          → Inertia SSR flag
 *
 * Runtime is Laravel Herd (native Windows) — no Docker, no Sail, no WSL.
 *
 * Usage:
 *   npm run syn             # regenerate .cursor/ (exit 1 if doc drift)
 *   npm run syn:check       # verify only, never write (CI / pre-commit gate)
 *
 * No external dependencies — runs on plain Node.
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  statSync,
  unlinkSync,
} from 'node:fs';
import { join, resolve, dirname, relative, sep, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const CHECK_ONLY = process.argv.includes('--check');
const QUIET = process.argv.includes('--quiet');

const GENERATED_MARKER = 'GENERATED by `npm run syn`';
const GENERATED_BANNER = `<!-- ${GENERATED_MARKER} — edit \`.claude/\` and re-run. DO NOT EDIT. -->`;

/** Everything under `.claude/` that must never reach `.cursor/` or the drift scan. */
const CLAUDE_PRIVATE = new Set(['projects', 'settings.json', 'settings.local.json']);

const c = {
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  cyan: (s) => `\x1b[36m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
};

const log = (...args) => {
  if (!QUIET) {
    console.log(...args);
  }
};

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const exists = (rel) => existsSync(join(ROOT, rel));
const readJson = (rel) => JSON.parse(read(rel));

// ------------------------------------------------------------------
// Helpers
// ------------------------------------------------------------------
function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { frontmatter: {}, body: content };
  }

  const frontmatter = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^([\w-]+)\s*:\s*(.+)$/);
    if (m) {
      frontmatter[m[1]] = m[2].replace(/^['"]|['"]$/g, '').trim();
    }
  }

  return { frontmatter, body: match[2] };
}

function extractFirstHeading(body) {
  const m = body.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}

function relPath(abs) {
  return relative(ROOT, abs).split(sep).join('/');
}

/** Deterministic recursive file listing — sorted so output never depends on FS order. */
function listFiles(absDir) {
  const out = [];
  if (!existsSync(absDir)) {
    return out;
  }

  for (const entry of readdirSync(absDir).sort()) {
    const abs = join(absDir, entry);
    if (statSync(abs).isDirectory()) {
      out.push(...listFiles(abs));
    } else {
      out.push(abs);
    }
  }

  return out;
}

// ------------------------------------------------------------------
// 1. Ground truth — derived from the real code
// ------------------------------------------------------------------
function detectUiLibrary(deps) {
  if (deps.primevue) {
    return { name: 'primevue', version: deps.primevue };
  }
  if (deps['reka-ui']) {
    return { name: 'shadcn-vue (reka-ui)', version: deps['reka-ui'] };
  }
  return { name: 'unknown', version: 'absent' };
}

function detectFacts() {
  const pkg = readJson('package.json');
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const composer = readJson('composer.json');
  const req = { ...composer.require, ...composer['require-dev'] };
  const appTs = exists('resources/js/app.ts') ? read('resources/js/app.ts') : '';
  const viteConfig = exists('vite.config.ts') ? read('vite.config.ts') : '';
  const componentsJson = exists('components.json') ? readJson('components.json') : null;

  const ui = detectUiLibrary(deps);

  return {
    runtime: 'Laravel Herd (native Windows) — no Docker, no Sail, no WSL',
    php: req.php ?? 'unknown',
    laravel: req['laravel/framework'] ?? 'unknown',
    inertiaLaravel: req['inertiajs/inertia-laravel'] ?? 'unknown',
    vue: deps.vue ?? 'unknown',
    uiLibrary: ui.name,
    uiVersion: ui.version,
    shadcnStyle: componentsJson?.style ?? 'n/a',
    iconLibrary: componentsJson?.iconLibrary ?? (deps.primeicons ? 'primeicons' : 'unknown'),
    inertiaVue: deps['@inertiajs/vue3'] ?? 'absent',
    tailwind: Boolean(deps.tailwindcss),
    // Pest ships PHPUnit as a transitive dep — check Pest FIRST or the answer is always "phpunit".
    testRunner: req['pestphp/pest'] ? 'pest' : req['phpunit/phpunit'] ? 'phpunit' : 'unknown',
    unstyled: Boolean(deps.primevue) && /unstyled\s*:\s*true/.test(appTs),
    hasZod: Boolean(deps.zod),
    hasPinia: Boolean(deps.pinia),
    hasPiniaColada: Boolean(deps['@pinia/colada']),
    hasIdeHelper: Boolean(req['barryvdh/laravel-ide-helper']),
    hasScramble: Boolean(req['dedoc/scramble']),
    inertiaSsr: /inertia\s*\(\s*\{\s*ssr\s*:\s*true/.test(viteConfig),
  };
}

// ------------------------------------------------------------------
// 2. Collect AI doc files (the things that drift)
// ------------------------------------------------------------------
function collectDocs() {
  const docs = [];
  const claudeDir = join(ROOT, '.claude');

  if (existsSync(claudeDir)) {
    for (const entry of readdirSync(claudeDir).sort()) {
      if (CLAUDE_PRIVATE.has(entry)) continue;
      const abs = join(claudeDir, entry);
      if (statSync(abs).isDirectory()) {
        docs.push(...listFiles(abs).filter((f) => f.endsWith('.md')));
      } else if (entry.endsWith('.md')) {
        docs.push(abs);
      }
    }
  }

  for (const f of ['CLAUDE.md', 'AGENTS.md']) {
    if (exists(f)) docs.push(join(ROOT, f));
  }

  return docs;
}

// ------------------------------------------------------------------
// 3. Drift rules — docs that contradict the code
// ------------------------------------------------------------------
const NEG = /not used|not installed|no longer|never\b|❌|\bNOT\b|forbidden|denied|wrong\b|isn'?t used|deprecated|legacy/i;

function buildRules(facts) {
  const rules = [];

  if (facts.testRunner === 'pest') {
    rules.push({
      id: 'test-runner',
      bad: /\b(vitest|playwright|PHPUnit class-style)\b/i,
      allow: NEG,
      msg: 'Test runner is Pest 5 but a doc still references another runner.',
    });
  }

  // Runtime is Herd — Sail / Docker must never be prescribed (see rules.md ABSOLUTE).
  // A line that also names Herd is stating the rule, not breaking it.
  rules.push({
    id: 'sail-docker',
    bad: /vendor\/bin\/sail|docker compose exec|laravel sail|\bWSL\b/i,
    allow: new RegExp(`${NEG.source}|\\bherd\\b|\\bno (docker|sail|wsl)\\b`, 'i'),
    msg: 'Runtime is Laravel Herd (native Windows) — Sail / Docker / WSL must not be prescribed.',
  });

  if (facts.uiLibrary === 'primevue' && facts.unstyled) {
    rules.push({
      id: 'primevue-mode',
      bad: /preset\s*:/,
      allow: NEG,
      msg: 'PrimeVue runs in unstyled mode but a doc still shows a theme preset.',
    });
  }

  rules.push({
    id: 'data-theme',
    bad: /data-theme/,
    allow: /never|NOT|❌|no `data-theme`|absence of class/i,
    msg: 'Theme toggling uses only `.dark` on `<html>` — `data-theme` is forbidden.',
  });

  rules.push({
    id: 'angular-stack',
    bad: /\b(@angular\/|Angular v\d|standalone\s*:\s*true)/,
    allow: NEG,
    msg: 'Stack is Vue 3 + Inertia but a doc references Angular patterns.',
  });

  return rules;
}

function scanDrift(docs, facts) {
  const rules = buildRules(facts);
  const findings = [];

  for (const abs of docs) {
    const rel = relPath(abs);
    const lines = read(rel).split(/\r?\n/);

    lines.forEach((line, i) => {
      for (const rule of rules) {
        if (rule.bad.test(line) && !rule.allow.test(line)) {
          findings.push({ rule: rule.id, msg: rule.msg, file: rel, line: i + 1, text: line.trim() });
        }
      }
    });
  }

  return findings;
}

/**
 * Whole-stack mismatches. Reported as warnings, not per-line findings — a single
 * wrong assumption in the docs would otherwise emit hundreds of identical lines.
 */
function scanStackWarnings(docs, facts) {
  const warnings = [];
  const mentions = (re) => docs.filter((abs) => re.test(read(relPath(abs))));

  if (facts.uiLibrary !== 'primevue') {
    const hits = mentions(/PrimeVue|Volt|primeicons|tailwindcss-primeui/i);
    if (hits.length > 0) {
      warnings.push({
        id: 'ui-library',
        msg:
          `Docs mandate PrimeVue v4 unstyled + Volt, but package.json installs "${facts.uiLibrary}" ` +
          `(${facts.uiVersion}) with components.json style "${facts.shadcnStyle}" and icons "${facts.iconLibrary}". ` +
          'Either migrate the code or rewrite the FRONTEND docs — the two disagree today.',
        files: hits.map(relPath),
      });
    }
  }

  return warnings;
}

// ------------------------------------------------------------------
// 4. Build the .cursor/ plan (path → content)
// ------------------------------------------------------------------
function factsMarkdown(facts) {
  const yn = (b) => (b ? 'yes' : 'no');
  return [
    '## Project ground truth (auto-detected from code)',
    '',
    '> Generated by `npm run syn` — do not edit by hand.',
    '',
    `- **Runtime:** ${facts.runtime}`,
    `- **PHP:** ${facts.php}`,
    `- **Laravel:** ${facts.laravel}`,
    `- **Inertia (Laravel):** ${facts.inertiaLaravel}`,
    `- **Vue:** ${facts.vue} | **Inertia (Vue):** ${facts.inertiaVue}`,
    `- **UI library:** ${facts.uiLibrary} ${facts.uiVersion} | **Icons:** ${facts.iconLibrary}`,
    `- **Tailwind v4:** ${yn(facts.tailwind)} | **Inertia SSR:** ${yn(facts.inertiaSsr)}`,
    `- **Test runner:** ${facts.testRunner}`,
    `- **Zod:** ${yn(facts.hasZod)} | **Pinia:** ${yn(facts.hasPinia)} | **Pinia Colada:** ${yn(facts.hasPiniaColada)}`,
    `- **IDE Helper:** ${yn(facts.hasIdeHelper)} | **Scramble:** ${yn(facts.hasScramble)}`,
    '',
  ].join('\n');
}

function ruleToMdc(sourceRel, content) {
  const { frontmatter, body } = parseFrontmatter(content);
  const alwaysApply =
    frontmatter.trigger === 'always_on' ||
    frontmatter.alwaysApply === 'true' ||
    frontmatter.alwaysApply === true;
  const description =
    frontmatter.description || extractFirstHeading(body) || `Synced from ${sourceRel}`;

  const lines = ['---', `alwaysApply: ${alwaysApply}`, `description: ${description}`];
  if (frontmatter.globs) {
    lines.push(`globs: ${frontmatter.globs}`);
  }
  lines.push('---', '', GENERATED_BANNER, '', body.trimEnd(), '');

  return lines.join('\n');
}

function withGeneratedBanner(content) {
  const { frontmatter, body } = parseFrontmatter(content);
  if (Object.keys(frontmatter).length === 0) {
    return `${GENERATED_BANNER}\n\n${content.trimEnd()}\n`;
  }

  const fm = Object.entries(frontmatter)
    .map(([k, v]) => `${k}: ${v}`)
    .join('\n');

  return `---\n${fm}\n---\n\n${GENERATED_BANNER}\n\n${body.trimEnd()}\n`;
}

/** Mirrors every .md under sourceRel into destRel, applying `transform`. */
function planMarkdownTree(plan, sourceRel, destRel, transform = withGeneratedBanner) {
  const sourceAbs = join(ROOT, sourceRel);
  if (!existsSync(sourceAbs)) {
    return;
  }

  for (const abs of listFiles(sourceAbs)) {
    if (!abs.endsWith('.md')) continue;
    const suffix = relPath(abs).slice(sourceRel.length + 1);
    plan.set(`${destRel}/${suffix}`, transform(read(relPath(abs)), relPath(abs)));
  }
}

/** Claude MCP entries → Cursor `.cursor/mcp.json` shape. */
function toCursorMcp(server) {
  if (server.type === 'http' || server.url) {
    return { url: server.url, ...(server.headers ? { headers: server.headers } : {}) };
  }

  return {
    command: server.command,
    ...(server.args ? { args: server.args } : {}),
    ...(server.env ? { env: server.env } : {}),
  };
}

function buildPlan(facts) {
  const plan = new Map();

  // Rules: .claude/rules/*.md → .cursor/rules/*.mdc
  const rulesDir = join(ROOT, '.claude', 'rules');
  if (existsSync(rulesDir)) {
    for (const entry of readdirSync(rulesDir).sort()) {
      if (!entry.endsWith('.md')) continue;
      const sourceRel = `.claude/rules/${entry}`;
      plan.set(`.cursor/rules/${entry.replace(/\.md$/, '.mdc')}`, ruleToMdc(sourceRel, read(sourceRel)));
    }
  }

  // CLAUDE.md → .cursor/rules/project-guidelines.mdc
  if (exists('CLAUDE.md')) {
    plan.set(
      '.cursor/rules/project-guidelines.mdc',
      [
        '---',
        'alwaysApply: true',
        'description: Project guidelines — framework versions, Herd runtime, Inertia, Pest conventions',
        '---',
        '',
        GENERATED_BANNER,
        '',
        read('CLAUDE.md').trimEnd(),
        '',
      ].join('\n'),
    );
  }

  // Skills: .claude/skills/** → .cursor/skills/**
  planMarkdownTree(plan, '.claude/skills', '.cursor/skills');

  // Top-level skill dirs that live outside skills/
  for (const dir of ['BACKEND-PHP', 'FRONTEND', 'OWASP']) {
    const skillRel = `.claude/${dir}/SKILL.md`;
    if (exists(skillRel)) {
      plan.set(`.cursor/skills/${dir}/SKILL.md`, withGeneratedBanner(read(skillRel)));
    }
  }

  // Commands + agents
  planMarkdownTree(plan, '.claude/commands', '.cursor/commands');
  planMarkdownTree(plan, '.claude/agents', '.cursor/agents');

  // MCP servers: .claude/settings.json + .mcp.json → .cursor/mcp.json
  const servers = {};
  if (exists('.mcp.json')) {
    Object.assign(servers, readJson('.mcp.json').mcpServers ?? {});
  }
  if (exists('.claude/settings.json')) {
    Object.assign(servers, readJson('.claude/settings.json').mcpServers ?? {});
  }
  if (Object.keys(servers).length > 0) {
    const mapped = {};
    for (const name of Object.keys(servers).sort()) {
      mapped[name] = toCursorMcp(servers[name]);
    }
    plan.set('.cursor/mcp.json', JSON.stringify({ mcpServers: mapped }, null, 2) + '\n');
  }

  // Machine-readable facts
  plan.set('.cursor/project-facts.json', JSON.stringify(facts, null, 2) + '\n');

  // README
  plan.set(
    '.cursor/README.md',
    [
      GENERATED_BANNER,
      '',
      '# .cursor — AI configuration (synced)',
      '',
      'Canonical source: `.claude/` + `CLAUDE.md`. Re-generate with:',
      '',
      '```bash',
      'npm run syn',
      '```',
      '',
      'A `PostToolUse` hook in `.claude/settings.json` runs this automatically whenever',
      'a file under `.claude/` (or `CLAUDE.md`) is edited, so `.cursor/` never goes stale.',
      '',
      '## Layout',
      '',
      '- `rules/*.mdc` — always-on and contextual rules (from `.claude/rules/` + `CLAUDE.md`)',
      '- `skills/**/SKILL.md` — domain skills (architecture, backend, frontend, OWASP)',
      '- `commands/*.md` — slash commands for Cursor',
      '- `agents/*.md` — agent definitions',
      '- `mcp.json` — MCP servers mirrored from `.claude/settings.json` + `.mcp.json`',
      '- `project-facts.json` — auto-detected stack versions',
      '',
      factsMarkdown(facts),
      '**Do not edit these files directly** — edit `.claude/` and run `npm run syn`.',
      '',
    ].join('\n'),
  );

  return plan;
}

// ------------------------------------------------------------------
// 5. Apply / verify the plan
// ------------------------------------------------------------------
function currentContent(rel) {
  return exists(rel) ? read(rel) : null;
}

/** Generated files no longer in the plan — deletions in .claude/ must propagate. */
function findStale(plan) {
  return listFiles(join(ROOT, '.cursor'))
    .map(relPath)
    .filter((rel) => !plan.has(rel))
    .filter((rel) => rel.endsWith('.json') || read(rel).includes(GENERATED_MARKER));
}

function diffPlan(plan) {
  const created = [];
  const updated = [];

  for (const [rel, content] of plan) {
    const current = currentContent(rel);
    if (current === null) {
      created.push(rel);
    } else if (current !== content) {
      updated.push(rel);
    }
  }

  return { created, updated, stale: findStale(plan) };
}

function applyPlan(plan, stale) {
  for (const [rel, content] of plan) {
    const abs = join(ROOT, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }

  for (const rel of stale) {
    unlinkSync(join(ROOT, rel));
  }
}

// ------------------------------------------------------------------
// Main
// ------------------------------------------------------------------
function main() {
  log(c.bold('\nsyn') + c.dim(` — .claude/ → .cursor/ (${CHECK_ONLY ? 'check only' : 'check + sync'})\n`));

  const facts = detectFacts();
  log(c.cyan('Ground truth:'));
  log(
    factsMarkdown(facts)
      .split('\n')
      .filter((l) => l.startsWith('- '))
      .join('\n'),
  );
  log('');

  const docs = collectDocs();
  const findings = scanDrift(docs, facts);
  const warnings = scanStackWarnings(docs, facts);

  if (findings.length === 0) {
    log(c.green(`✔ No drift across ${docs.length} AI doc file(s).`));
  } else {
    log(c.red(`✖ ${findings.length} drift issue(s) found:`));
    for (const f of findings) {
      log(`  ${c.red('•')} ${c.bold(f.file + ':' + f.line)} ${c.dim('[' + f.rule + ']')}`);
      log(`    ${f.msg}`);
      log(`    ${c.dim(f.text)}`);
    }
  }

  for (const w of warnings) {
    log('');
    log(`${c.yellow('⚠')} ${c.bold(w.id)} — ${w.msg}`);
    log(c.dim(`  ${w.files.length} doc file(s): ${w.files.join(', ')}`));
  }

  const plan = buildPlan(facts);
  const { created, updated, stale } = diffPlan(plan);
  const dirty = created.length + updated.length + stale.length;

  if (CHECK_ONLY) {
    if (dirty === 0) {
      log('\n' + c.green(`✔ .cursor/ is in sync (${plan.size} file(s)).`));
    } else {
      log('\n' + c.red(`✖ .cursor/ is out of sync — run \`npm run syn\`:`));
      for (const r of created) log(`  ${c.green('+')} ${r}`);
      for (const r of updated) log(`  ${c.yellow('~')} ${r}`);
      for (const r of stale) log(`  ${c.red('-')} ${r} ${c.dim('(stale)')}`);
    }
  } else {
    applyPlan(plan, stale);
    if (dirty === 0) {
      log('\n' + c.green(`✔ .cursor/ already up to date (${plan.size} file(s)).`));
    } else {
      log('\n' + c.green(`✔ Synced ${plan.size} file(s) to .cursor/ — ${dirty} change(s):`));
      for (const r of created) log(`  ${c.green('+')} ${r}`);
      for (const r of updated) log(`  ${c.yellow('~')} ${r}`);
      for (const r of stale) log(`  ${c.red('-')} ${r} ${c.dim('(pruned)')}`);
    }
  }

  log('');
  if (findings.length > 0) {
    log(c.red('Drift detected — update the docs in .claude/ (or the code) and re-run `npm run syn`.'));
    process.exit(1);
  }
  if (CHECK_ONLY && dirty > 0) {
    process.exit(1);
  }
}

main();
