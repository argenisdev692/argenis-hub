#!/usr/bin/env node
/**
 * syn:opencode — AI config sync (.claude/ → .opencode/ + opencode.json)
 * ------------------------------------------------------------------
 * `.claude/` + `AGENTS.md` are the SINGLE SOURCE OF TRUTH. This script
 * regenerates the `.opencode/` tree and the managed `mcp` / `instructions`
 * keys of `opencode.json` from them.
 *
 * Mapping (verified against https://opencode.ai/docs 2026-09-15):
 *   - `.claude/commands/*.md`          → `.opencode/commands/*.md` (as-is;
 *     frontmatter `description`/`agent`/`model` is already compatible)
 *   - `.claude/agents/*.md`            → `.opencode/agents/*.md` (as-is)
 *   - `.claude/skills/...SKILL.md`     → `.opencode/skills/...SKILL.md` (as-is;
 *     OpenCode also reads `.claude/skills/` natively, this is a mirror)
 *   - `.claude/{BACKEND-PHP,FRONTEND,OWASP}/SKILL.md`
 *     → `.opencode/skills/{backend-php,frontend,owasp}/SKILL.md`
 *     (OpenCode only discovers `skills/...SKILL.md`, so the top-level
 *     dirs need remapping + `name`/`description` frontmatter which
 *     OpenCode requires)
 *   - `.claude/rules/*.md`             → `.opencode/rules/*.md` + wired via
 *     `opencode.json` `instructions` (OpenCode has no native rules folder;
 *     `AGENTS.md` is auto-loaded, rules come through `instructions`)
 *   - `.claude/settings.json` + `.mcp.json` `mcpServers`
 *     → `opencode.json` `mcp` (`type: local` with `command[]` /
 *     `environment`, or `type: remote` with `url` / `headers`), except the
 *     servers listed in `OPENCODE_MCP_OVERRIDES`, which are written as-is
 *
 * Never copies: `.claude/projects/`, `.claude/settings*.json` (private).
 *
 * Usage:
 *   npm run syn:opencode        # regenerate .opencode/ + opencode.json
 *   npm run syn:opencode:check  # verify only, never write (CI gate)
 *
 * No external dependencies — runs on plain Node.
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  statSync,
  unlinkSync,
} from 'node:fs';
import { join, resolve, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const CHECK_ONLY = process.argv.includes('--check');
const QUIET = process.argv.includes('--quiet');

const GENERATED_MARKER = 'GENERATED by `npm run syn:opencode`';
const GENERATED_BANNER = `<!-- ${GENERATED_MARKER} — edit \`.claude/\` and re-run. DO NOT EDIT. -->`;

/** Everything under `.claude/` that must never reach `.opencode/`. */
const CLAUDE_PRIVATE = new Set(['projects', 'settings.json', 'settings.local.json']);

/** Top-level skill dirs remapped to valid OpenCode skill names. */
const TOP_LEVEL_SKILLS = {
  'BACKEND-PHP': 'backend-php',
  FRONTEND: 'frontend',
  OWASP: 'owasp',
};

const c = {
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  cyan: (s) => `\x1b[36m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
};

const log = (...args) => {
  if (!QUIET) {
    console.log(...args);
  }
};

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const exists = (rel) => existsSync(join(ROOT, rel));
const readJson = (rel) => JSON.parse(read(rel));

function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { frontmatter: {}, body: content };
  }

  const frontmatter = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^([\w-]+)\s*:\s*(.+)$/);
    if (m) {
      frontmatter[m[1]] = m[2].replace(/^['"]|['"]$/g, '').trim();
    }
  }

  return { frontmatter, body: match[2] };
}

function extractFirstHeading(body) {
  const m = body.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}

function relPath(abs) {
  return relative(ROOT, abs).split(sep).join('/');
}

/** Deterministic recursive file listing — sorted so output never depends on FS order. */
function listFiles(absDir) {
  const out = [];
  if (!existsSync(absDir)) {
    return out;
  }

  for (const entry of readdirSync(absDir).sort()) {
    const abs = join(absDir, entry);
    if (statSync(abs).isDirectory()) {
      out.push(...listFiles(abs));
    } else {
      out.push(abs);
    }
  }

  return out;
}

function withGeneratedBanner(content) {
  const { frontmatter, body } = parseFrontmatter(content);
  if (Object.keys(frontmatter).length === 0) {
    return `${GENERATED_BANNER}\n\n${content.trimEnd()}\n`;
  }

  const fm = Object.entries(frontmatter)
    .map(([k, v]) => `${k}: ${v}`)
    .join('\n');

  return `---\n${fm}\n---\n\n${GENERATED_BANNER}\n\n${body.trimEnd()}\n`;
}

/**
 * OpenCode requires `name` + `description` frontmatter on every SKILL.md
 * and `name` must match the directory name (`^[a-z0-9]+(-[a-z0-9]+)*$`).
 * Top-level `.claude/<DIR>/SKILL.md` files predate that contract, so inject
 * the missing fields instead of copying them verbatim.
 */
function toOpenCodeSkill(skillName, content, sourceRel) {
  const { frontmatter, body } = parseFrontmatter(content);
  const description =
    frontmatter.description || extractFirstHeading(body) || `Synced from ${sourceRel}`;

  const fm = { name: skillName, description, ...frontmatter };
  fm.name = skillName;
  fm.description = description;

  const fmText = Object.entries(fm)
    .map(([k, v]) => `${k}: ${v}`)
    .join('\n');

  return `---\n${fmText}\n---\n\n${GENERATED_BANNER}\n\n${body.trimEnd()}\n`;
}

/** Mirrors every .md under sourceRel into destRel, applying `transform`. */
function planMarkdownTree(plan, sourceRel, destRel, transform = withGeneratedBanner) {
  const sourceAbs = join(ROOT, sourceRel);
  if (!existsSync(sourceAbs)) {
    return;
  }

  for (const abs of listFiles(sourceAbs)) {
    if (!abs.endsWith('.md')) {
      continue;
    }
    const suffix = relPath(abs).slice(sourceRel.length + 1);
    plan.set(`${destRel}/${suffix}`, transform(read(relPath(abs)), relPath(abs)));
  }
}

/**
 * OpenCode-only MCP entries that win over the one generated from
 * `.mcp.json` / `.claude/settings.json`. Use it when OpenCode should reach a
 * server differently from Claude Code — e.g. Tavily's hosted endpoint instead
 * of a local `npx tavily-mcp`. `{env:NAME}` is OpenCode's own substitution
 * syntax.
 */
const OPENCODE_MCP_OVERRIDES = {
  github: {
    type: 'remote',
    url: 'https://api.githubcopilot.com/mcp/',
    headers: {
      Authorization: 'Bearer {env:GITHUB_TOKEN}',
    },
  },
  tavily: {
    type: 'remote',
    url: 'https://mcp.tavily.com/mcp',
    headers: {
      Authorization: 'Bearer {env:TAVILY_API_KEY}',
    },
  },
};

/** Claude/`mcpServers` entry → OpenCode `mcp` entry (`type: local | remote`). */
function toOpenCodeMcp(server) {
  if (server.type === 'http' || server.url) {
    return {
      type: 'remote',
      url: server.url,
      ...(server.headers ? { headers: server.headers } : {}),
    };
  }

  const command = [server.command, ...(server.args ?? [])].filter(Boolean);
  return {
    type: 'local',
    command,
    ...(server.env ? { environment: server.env } : {}),
  };
}

function buildPlan() {
  const plan = new Map();

  // Rules: .claude/rules/*.md → .opencode/rules/*.md
  planMarkdownTree(plan, '.claude/rules', '.opencode/rules');

  // Skills: .claude/skills/** → .opencode/skills/**
  planMarkdownTree(plan, '.claude/skills', '.opencode/skills');

  // Top-level skill dirs that live outside skills/
  for (const [dir, skillName] of Object.entries(TOP_LEVEL_SKILLS)) {
    const skillRel = `.claude/${dir}/SKILL.md`;
    if (exists(skillRel)) {
      plan.set(
        `.opencode/skills/${skillName}/SKILL.md`,
        toOpenCodeSkill(skillName, read(skillRel), skillRel),
      );
    }
  }

  // Commands + agents (OpenCode paths are plural: commands/, agents/)
  planMarkdownTree(plan, '.claude/commands', '.opencode/commands');
  planMarkdownTree(plan, '.claude/agents', '.opencode/agents');

  // opencode.json — preserve user keys, manage only mcp + instructions.
  const servers = {};
  if (exists('.mcp.json')) {
    Object.assign(servers, readJson('.mcp.json').mcpServers ?? {});
  }
  if (exists('.claude/settings.json')) {
    Object.assign(servers, readJson('.claude/settings.json').mcpServers ?? {});
  }
  const mcp = {};
  for (const name of Object.keys(servers).sort()) {
    mcp[name] = OPENCODE_MCP_OVERRIDES[name] ?? toOpenCodeMcp(servers[name]);
  }

  const ruleFiles = [...plan.keys()]
    .filter((rel) => rel.startsWith('.opencode/rules/'))
    .sort();

  let base = {};
  if (exists('opencode.json')) {
    try {
      base = readJson('opencode.json');
    } catch {
      base = {};
    }
  }
  const next = { ...base };
  if (Object.keys(mcp).length > 0) {
    next.mcp = mcp;
  } else {
    delete next.mcp;
  }
  next.instructions = ruleFiles.map((rel) => `./${rel}`);
  if (!next.$schema) {
    next.$schema = 'https://opencode.ai/config.json';
  }
  plan.set('opencode.json', JSON.stringify(next, null, 2) + '\n');

  // README
  plan.set(
    '.opencode/README.md',
    [
      GENERATED_BANNER,
      '',
      '# .opencode — AI configuration (synced)',
      '',
      'Canonical source: `.claude/` + `AGENTS.md`. Re-generate with:',
      '',
      '```bash',
      'npm run syn:opencode',
      '```',
      '',
      '## Layout',
      '',
      '- `rules/*.md` — synced from `.claude/rules/`, wired via `opencode.json` `instructions`',
      '  (`AGENTS.md` at the repo root is auto-loaded by OpenCode, no wiring needed)',
      '- `skills/**/SKILL.md` — domain skills (architecture, backend, frontend, OWASP)',
      '- `commands/*.md` — slash commands (`/name`)',
      '- `agents/*.md` — subagents (`@name`)',
      '',
      '**Do not edit these files directly** — edit `.claude/` and run `npm run syn:opencode`.',
      '',
    ].join('\n'),
  );

  return plan;
}

function currentContent(rel) {
  return exists(rel) ? read(rel) : null;
}

/** Generated files no longer in the plan — deletions in .claude/ must propagate. */
function findStale(plan) {
  const dirs = [join(ROOT, '.opencode')];
  const stale = [];
  for (const dir of dirs) {
    for (const abs of listFiles(dir)) {
      const rel = relPath(abs);
      if (!plan.has(rel)) {
        const content = read(rel);
        if (rel.endsWith('.json') || content.includes(GENERATED_MARKER)) {
          stale.push(rel);
        }
      }
    }
  }
  // opencode.json is managed in place — never prune it as stale.
  return stale.filter((rel) => rel !== 'opencode.json');
}

function diffPlan(plan) {
  const created = [];
  const updated = [];

  for (const [rel, content] of plan) {
    const current = currentContent(rel);
    if (current === null) {
      created.push(rel);
    } else if (current !== content) {
      updated.push(rel);
    }
  }

  return { created, updated, stale: findStale(plan) };
}

function applyPlan(plan, stale) {
  for (const [rel, content] of plan) {
    const abs = join(ROOT, rel);
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
  }

  for (const rel of stale) {
    unlinkSync(join(ROOT, rel));
  }
}

function main() {
  log(c.bold('\nsyn:opencode') + c.dim(` — .claude/ → .opencode/ (${CHECK_ONLY ? 'check only' : 'check + sync'})\n`));

  const plan = buildPlan();
  const { created, updated, stale } = diffPlan(plan);
  const dirty = created.length + updated.length + stale.length;

  if (CHECK_ONLY) {
    if (dirty === 0) {
      log('\n' + c.green(`✔ .opencode/ is in sync (${plan.size} file(s)).`));
    } else {
      log('\n' + c.red('✖ .opencode/ is out of sync — run `npm run syn:opencode`:'));
      for (const r of created) {
        log(`  ${c.green('+')} ${r}`);
      }
      for (const r of updated) {
        log(`  ${c.yellow('~')} ${r}`);
      }
      for (const r of stale) {
        log(`  ${c.red('-')} ${r} ${c.dim('(stale)')}`);
      }
      process.exit(1);
    }
  } else {
    applyPlan(plan, stale);
    if (dirty === 0) {
      log('\n' + c.green(`✔ .opencode/ already up to date (${plan.size} file(s)).`));
    } else {
      log('\n' + c.green(`✔ Synced ${plan.size} file(s) to .opencode/ — ${dirty} change(s):`));
      for (const r of created) {
        log(`  ${c.green('+')} ${r}`);
      }
      for (const r of updated) {
        log(`  ${c.yellow('~')} ${r}`);
      }
      for (const r of stale) {
        log(`  ${c.red('-')} ${r} ${c.dim('(pruned)')}`);
      }
    }
  }

  log('');
}

main();
